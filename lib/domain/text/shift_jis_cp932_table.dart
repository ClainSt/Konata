/// 纯 Dart 完整 Shift-JIS / CP932 码表（覆盖全部 9604 个日文双字节汉字/假名/符号与半角片假名）。
///
/// 采用压缩 Base64 扁平 UTF-16 查表结构，空载零堆内存占用，首次解码日文传统字幕或 CUE 时按需解压为
/// `Uint16List` 并实现 O(1) 索引查询。
